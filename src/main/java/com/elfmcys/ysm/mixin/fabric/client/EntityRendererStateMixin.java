package com.elfmcys.ysm.mixin.fabric.client;

import com.elfmcys.ysm.platform.render.YsmRenderStateKeys;
import net.minecraft.client.renderer.entity.EntityRenderer;
import net.minecraft.client.renderer.entity.state.EntityRenderState;
import net.minecraft.world.entity.Entity;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfoReturnable;

/** Remembers which entity (and partial tick) a render state was extracted from (see YsmRenderStateKeys). */
@Mixin(EntityRenderer.class)
public abstract class EntityRendererStateMixin {
    @Inject(method = "createRenderState(Lnet/minecraft/world/entity/Entity;F)Lnet/minecraft/client/renderer/entity/state/EntityRenderState;",
        at = @At("RETURN"))
    private void ysm$rememberEntity(Entity entity, float partialTicks, CallbackInfoReturnable<EntityRenderState> cir) {
        YsmRenderStateKeys.setEntity(cir.getReturnValue(), entity, partialTicks);
    }
}
