package com.elfmcys.ysm.platform.event.forge;

import com.elfmcys.ysm.platform.event.Event;

import java.util.concurrent.CompletableFuture;

/** Fabric port: posted from the Fabric entry point; enqueued work runs immediately on the init thread. */
public class FMLCommonSetupEvent extends Event implements IModBusEvent {
    public CompletableFuture<Void> enqueueWork(Runnable work) {
        work.run();
        return CompletableFuture.completedFuture(null);
    }
}
