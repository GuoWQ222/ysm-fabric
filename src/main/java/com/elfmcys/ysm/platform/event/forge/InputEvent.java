package com.elfmcys.ysm.platform.event.forge;

import com.elfmcys.ysm.platform.event.Event;

/** Fabric port: Forge input events, posted by mixin.fabric.client.InputEventsMixin / MouseButtonEventsMixin. */
public class InputEvent extends Event {
    public static class Key extends InputEvent {
        private final int key, scanCode, action, modifiers;

        public Key(int key, int scanCode, int action, int modifiers) {
            this.key = key;
            this.scanCode = scanCode;
            this.action = action;
            this.modifiers = modifiers;
        }

        public int getKey() {
            return key;
        }

        public int getScanCode() {
            return scanCode;
        }

        public int getAction() {
            return action;
        }

        public int getModifiers() {
            return modifiers;
        }
    }

    public static class MouseButton extends InputEvent {
        private final int button, action, modifiers;

        protected MouseButton(int button, int action, int modifiers) {
            this.button = button;
            this.action = action;
            this.modifiers = modifiers;
        }

        public int getButton() {
            return button;
        }

        public int getAction() {
            return action;
        }

        public int getModifiers() {
            return modifiers;
        }

        public static class Post extends MouseButton {
            public Post(int button, int action, int modifiers) {
                super(button, action, modifiers);
            }
        }
    }
}
