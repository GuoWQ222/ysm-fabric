package com.elfmcys.ysm.platform.event.forge;

import com.elfmcys.ysm.platform.event.Event;
import net.minecraft.server.MinecraftServer;

/** Fabric port: posted from Fabric server lifecycle callbacks. */
public class ServerAboutToStartEvent extends Event {
    private final MinecraftServer server;

    public ServerAboutToStartEvent(MinecraftServer server) {
        this.server = server;
    }

    public MinecraftServer getServer() {
        return server;
    }
}
